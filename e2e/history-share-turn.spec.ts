import { expect, test } from '@playwright/test'

test('shares the complete turn across evicted pages without replacing the reader window', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/e2e-fixtures/history-load-fixture.html?shareLongTurn=1')
    await expect(page.getByText('Fixture message 1200', { exact: true })).toBeInViewport()
    await page.waitForTimeout(2000)
    expect(await page.evaluate(() => window.__probe.windowState().messageCount)).toBe(200)
    await expect(page.getByText('Export this complete long turn', { exact: true })).toHaveCount(0)
    const before = await page.evaluate(() => window.__probe.windowState())
    await page.getByText('Export passage 1199: complete history content.', { exact: true }).hover()
    await page.locator('[data-hapi-message-role="assistant"]').getByRole('button', { name: 'Share turn as image', exact: true }).last().click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    await expect(dialog.getByText('Export this complete long turn', { exact: true })).toHaveCount(1)
    await expect(dialog.getByText('Export passage 602: complete history content.', { exact: true })).toHaveCount(1)
    await expect(dialog.getByText('Export passage 1199: complete history content.', { exact: true })).toHaveCount(1)
    await expect(dialog.getByText('Fixture message 1200', { exact: true })).toHaveCount(0)
    await expect(dialog.locator('p').filter({ hasText: /^Export passage \d+: complete history content\.$/ })).toHaveCount(598)
    expect(await page.evaluate(() => window.__probe.windowState())).toEqual(before)
    const requests = await page.evaluate(() => window.__probe.requests)
    expect(requests.filter(r => r.direction === 'context')).toHaveLength(1)
    expect(requests.filter(r => r.direction === 'before').length).toBeGreaterThan(0)
    expect(requests.filter(r => r.direction === 'after').length).toBeGreaterThan(0)
    expect(requests.every(r => (r.limit ?? 200) <= 200)).toBe(true)
    await dialog.getByRole('button', { name: 'Close', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByText('Export this complete long turn', { exact: true })).toHaveCount(0)
    expect(await page.locator('[data-hapi-virtual-message]').count()).toBeLessThanOrEqual(40)
})

test('cancelling a held complete-turn read prevents a late preview', async ({ page }) => {
    await page.goto('/e2e-fixtures/history-load-fixture.html?shareLongTurn=1')
    await expect(page.getByText('Fixture message 1200', { exact: true })).toBeInViewport()
    await page.waitForTimeout(2000)
    await page.evaluate(() => window.__probe.holdContext())
    await page.getByText('Export passage 1199: complete history content.', { exact: true }).hover()
    await page.locator('[data-hapi-message-role="assistant"]').getByRole('button', { name: 'Share turn as image', exact: true }).last().click()
    await expect(page.getByText('Preparing the complete turn…')).toBeVisible()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.evaluate(() => window.__probe.releaseContext())
    await page.waitForTimeout(300)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    expect(await page.evaluate(() => window.__probe.requests.filter(r => r.direction === 'before').length)).toBe(0)
})

