for (const failure of [false, true]) {
    test(`complete-turn export waits for an offscreen image and ${failure ? 'reports its failure' : 'retains it after capture unmounts'}`, async ({ page }) => {
        await page.goto(`/e2e-fixtures/history-load-fixture.html?shareLongTurn=1&shareSlowImage=1${failure ? '&shareImageFailure=1' : ''}`)
        await expect(page.getByText('Fixture message 1200', { exact: true })).toBeInViewport()
        await page.waitForTimeout(2000)
        expect(await page.evaluate(() => window.__probe.mediaReads)).toBe(0)
        await page.getByText('Export passage 1199: complete history content.', { exact: true }).hover()
        await page.locator('[data-hapi-message-role="assistant"]').getByRole('button', { name: 'Share turn as image', exact: true }).last().click()
        if (failure) {
            await expect(page.getByRole('alert').getByText('Could not load this turn. Please try again.')).toBeVisible()
            await expect(page.getByRole('dialog')).toHaveCount(0)
        } else {
            const dialog = page.getByRole('dialog')
            await expect(dialog).toBeVisible()
            const image = dialog.getByRole('img', { name: 'share-image.svg', exact: true })
            await expect(image).toBeAttached()
            expect(await image.getAttribute('src')).toMatch(/^data:image\/svg\+xml/)
            await expect.poll(() => image.evaluate(element => (element as HTMLImageElement).naturalWidth)).toBe(80)
            await page.waitForTimeout(300)
            expect(await image.evaluate(element => (element as HTMLImageElement).complete)).toBe(true)
            await dialog.getByRole('button', { name: 'Close', exact: true }).click()
            await expect(image).toHaveCount(0)
        }
        expect(await page.evaluate(() => window.__probe.mediaReads)).toBe(1)
    })
}

