test('history epoch change during export paging cancels the old capture', async ({ page }) => {
    await page.goto('/e2e-fixtures/history-load-fixture.html?shareLongTurn=1')
    await expect(page.getByText('Fixture message 1200', { exact: true })).toBeInViewport()
    await page.waitForTimeout(2000)
    await page.evaluate(() => window.__probe.holdBefore())
    await page.getByText('Export passage 1199: complete history content.', { exact: true }).hover()
    await page.locator('[data-hapi-message-role="assistant"]').getByRole('button', { name: 'Share turn as image', exact: true }).last().click()
    await expect.poll(() => page.evaluate(() => window.__probe.requests.filter(r => r.direction === 'before').length)).toBeGreaterThan(0)
    await page.evaluate(() => window.__probe.remoteRewindTo(1100))
    await expect(page.getByText('Preparing the complete turn…')).toHaveCount(0)
    await page.evaluate(() => window.__probe.releaseBefore())
    await page.waitForTimeout(300)
    await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('downloads an image containing offscreen user, response and generated media', async ({ page }, testInfo) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/e2e-fixtures/history-load-fixture.html?shareLongTurn=1&shareSlowImage=1&shareMediaExport=1')
    await expect(page.getByText('Fixture message 1200', { exact: true })).toBeInViewport()
    await page.waitForTimeout(2000)
    await page.getByText('Export passage 1199: complete history content.', { exact: true }).hover()
    await page.locator('[data-hapi-message-role="assistant"]').getByRole('button', { name: 'Share turn as image', exact: true }).last().click()
    const dialog = page.getByRole('dialog')
    await expect(dialog.getByText('Export this complete long turn', { exact: true })).toBeVisible()
    await expect(dialog.getByRole('img', { name: 'share-image.svg', exact: true })).toBeAttached()
    const downloadPromise = page.waitForEvent('download')
    await dialog.getByRole('button', { name: 'Download', exact: true }).click()
    const download = await downloadPromise
    const path = testInfo.outputPath('complete-turn-media-export.png')
    await download.saveAs(path)
    const { readFile } = await import('node:fs/promises')
    const bytes = await readFile(path)
    expect(bytes.subarray(1, 4).toString()).toBe('PNG')
    expect(bytes.readUInt32BE(16)).toBe(1920)
    expect(bytes.readUInt32BE(20)).toBeGreaterThan(300)
    expect(bytes.byteLength).toBeGreaterThan(10_000)
})
