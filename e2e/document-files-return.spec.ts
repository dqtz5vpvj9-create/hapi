import { expect, test } from '@playwright/test'

for (const width of [390, 1440]) {
    test(`returns from a binary preview to the same expanded file list at ${width}px`, async ({ page }) => {
        await page.setViewportSize({ width, height: 844 })
        await page.goto('/e2e-fixtures/workspace-fixture.html?panes=1&fileBrowser=1')
        await page.getByRole('button', { name: 'Pane actions', exact: true }).click()
        await page.getByRole('menuitem', { name: 'Project files', exact: true }).click()
        const panel = page.locator('.session-workspace-panel:visible')
        await panel.getByRole('button', { name: 'build', exact: true }).click()
        const file = panel.getByText('Readify.apk', { exact: true })
        await file.scrollIntoViewIfNeeded()
        const scroll = panel.locator('[data-hapi-session-files-scroll]')
        const top = await scroll.evaluate(element => element.scrollTop)
        expect(top).toBeGreaterThan(0)
        const sourceId = await panel.evaluate(element => element.closest('[data-pane-id]')!.getAttribute('data-pane-id'))
        let retainedList = await scroll.elementHandle()
        const reads = () => page.evaluate(() => window.__workspaceFixture.requests.filter(path => path.includes('/directory?')).length)
        let retainedReads = await reads()

        for (let visit = 0; visit < 3; visit++) {
            await file.click()
            const document = page.locator('.document-surface:visible')
            await expect(document).toContainText('This format cannot be edited')
            await document.getByRole('button', { name: 'Project files', exact: true }).click()
            await expect(panel).toBeVisible()
            await expect(page.locator(`[data-pane-id="${sourceId}"]`)).toHaveAttribute('data-focused', 'true')
            await expect(file).toBeVisible()
            if (visit > 0) expect(await scroll.evaluate((element, original) => element === original, retainedList)).toBe(true)
            expect(await scroll.evaluate(element => element.scrollTop)).toBe(top)
            if (visit > 0) expect(await reads()).toBe(retainedReads)
            else {
                await retainedList?.dispose()
                retainedList = await scroll.elementHandle()
                retainedReads = await reads()
            }
        }
        expect(await page.evaluate(() => window.__workspaceFixture.sends)).toEqual([])
        expect(await page.evaluate(() => window.__workspaceFixture.unhandled)).toEqual([])
        await retainedList?.dispose()
    })

    test(`opens Project files from a restored document with no live source browser at ${width}px`, async ({ page }) => {
        await page.setViewportSize({ width, height: 844 })
        await page.goto('/e2e-fixtures/workspace-fixture.html?panes=1&documents=1&fileBrowser=1')
        const document = page.locator('.document-surface:visible')
        await expect(document).toHaveAttribute('data-document-state', 'ready')
        await page.reload()
        await document.getByRole('button', { name: 'Project files', exact: true }).click()
        const panel = page.locator('.session-workspace-panel:visible')
        await expect(panel.getByRole('button', { name: 'build', exact: true })).toBeVisible()
        await panel.getByRole('button', { name: 'Back', exact: true }).click()
        await expect(document).toHaveAttribute('data-document-state', 'ready')
        expect(await page.evaluate(() => window.__workspaceFixture.sends)).toEqual([])
    })

    test(`preserves an unsaved edit when returning to files at ${width}px`, async ({ page }) => {
        await page.setViewportSize({ width, height: 844 })
        await page.goto('/e2e-fixtures/workspace-fixture.html?panes=1&fileBrowser=1')
        await page.getByRole('button', { name: 'Pane actions', exact: true }).click()
        await page.getByRole('menuitem', { name: 'Project files', exact: true }).click()
        const panel = page.locator('.session-workspace-panel:visible')
        await panel.getByRole('button', { name: 'build', exact: true }).click()
        await panel.getByText('PLAN.md', { exact: true }).click()
        const document = page.locator('.document-surface:visible')
        await expect(document).toHaveAttribute('data-document-state', 'ready')
        await document.getByRole('button', { name: 'Edit', exact: true }).click()
        const editor = document.locator('.cm-content')
        await editor.click(); await editor.press('Control+End'); await editor.pressSequentially('\nKeep this edit')
        await document.getByRole('button', { name: 'Project files', exact: true }).click()
        await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
        await expect(editor).toContainText('Keep this edit')
        await document.getByRole('button', { name: 'Project files', exact: true }).click()
        await page.getByRole('dialog').getByRole('button', { name: 'Keep local draft', exact: true }).click()
        await expect(panel.getByText('PLAN.md', { exact: true })).toBeVisible()
        await page.keyboard.press('Control+b'); await page.keyboard.press('o')
        await expect(document.locator('.cm-content')).toContainText('Keep this edit')
        expect(await page.evaluate(() => window.__workspaceFixture.fileWrites)).toEqual([])
        expect(await page.evaluate(() => window.__workspaceFixture.sends)).toEqual([])
    })
}
