test('a history reset removing the focused directory item returns focus to search', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/e2e-fixtures/history-load-fixture.html?outlineVirtual=1')
    await expect(page.getByText('Fixture message 1200', { exact: true })).toBeVisible()
    await page.waitForTimeout(2000)
    await page.getByRole('button', { name: 'Open conversation outline', exact: true }).click()
    const panel = page.getByRole('complementary', { name: 'Outline', exact: true })
    await panel.getByRole('button', { name: /Fixture message 1001$/ }).focus()
    await page.evaluate(() => window.__probe.remoteRewindTo(1000))
    await expect(panel.getByRole('button', { name: /Fixture message 1001$/ })).toHaveCount(0)
    await expect(panel.getByRole('searchbox', { name: 'Search outline items' })).toBeFocused()
    await expect(panel.getByRole('button', { name: /Fixture message 801$/ })).toBeVisible()
})

test('removing an explicitly blurred directory item does not move focus back into the directory', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/e2e-fixtures/history-load-fixture.html?outlineVirtual=1')
    await expect(page.getByText('Fixture message 1200', { exact: true })).toBeVisible()
    await page.waitForTimeout(2000)
    await page.getByRole('button', { name: 'Open conversation outline', exact: true }).click()
    const panel = page.getByRole('complementary', { name: 'Outline', exact: true })
    const item = panel.getByRole('button', { name: /Fixture message 1001$/ })
    await item.focus()
    await item.evaluate(element => element.blur())
    expect(await page.evaluate(() => document.activeElement === document.body)).toBe(true)
    await page.evaluate(() => window.__probe.remoteRewindTo(1000))
    await expect(item).toHaveCount(0)
    await expect(panel.getByRole('button', { name: /Fixture message 801$/ })).toBeVisible()
    await expect(panel.getByRole('searchbox', { name: 'Search outline items' })).not.toBeFocused()
    expect(await page.evaluate(() => document.activeElement === document.body)).toBe(true)
})
