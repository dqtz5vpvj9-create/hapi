test('metadata pages survive reopening while a fresh cursor chain bridges cached labels', async ({ page }) => {
    await page.goto('/e2e-fixtures/history-load-fixture.html?coldInitial=1&outlineVirtual=1')
    await expect(page.getByText('Fixture message 1200', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Open conversation outline', exact: true }).click()
    const panel = page.getByRole('complementary', { name: 'Outline' })
    await expect(panel.locator('[data-outline-count]')).toHaveAttribute('data-outline-count', '100')
    await panel.getByRole('button', { name: 'Load earlier', exact: true }).click()
    await expect(panel.locator('[data-outline-count]')).toHaveAttribute('data-outline-count', '200')
    await panel.getByRole('button', { name: 'Close', exact: true }).click()
    await page.getByRole('button', { name: 'Open conversation outline', exact: true }).click()
    await expect(panel.getByRole('button', { name: 'Load earlier', exact: true })).toBeEnabled()
    await panel.getByRole('button', { name: 'Load earlier', exact: true }).click()
    await expect(panel.locator('[data-outline-count]')).toHaveAttribute('data-outline-count', '300')
    expect(await page.evaluate(() => window.__probe.requests.filter(row => row.direction === 'outline').map(row => row.beforeSeq))).toEqual([null, 1101, null, 1101, 1001])
    expect(await page.evaluate(() => window.__probe.requests.filter(row => row.direction === 'before' || row.direction === 'context'))).toEqual([])
    expect(await page.evaluate(() => window.__probe.windowState().oldestSeq)).toBe(1181)
})


test('reopening after two hundred remote questions bridges the new-head gap before exhaustion', async ({ page }) => {
    await page.goto('/e2e-fixtures/history-load-fixture.html?coldInitial=1&outlineVirtual=1')
    await expect(page.getByText('Fixture message 1200', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Open conversation outline', exact: true }).click()
    const panel = page.getByRole('complementary', { name: 'Outline' })
    await expect(panel.locator('[data-outline-count]')).toHaveAttribute('data-outline-count', '100')
    await panel.getByRole('button', { name: 'Close', exact: true }).click()
    const before = await page.evaluate(() => window.__probe.windowState())
    await page.evaluate(() => { for (let i = 0; i < 200; i++) window.__probe.appendRemoteMessage(false) })
    await page.getByRole('button', { name: 'Open conversation outline', exact: true }).click()
    await expect(panel.locator('[data-outline-count]')).toHaveAttribute('data-outline-count', '200')
    await panel.getByRole('button', { name: 'Load earlier', exact: true }).click()
    await expect(panel.locator('[data-outline-count]')).toHaveAttribute('data-outline-count', '300')
    expect(await page.evaluate(() => window.__probe.requests.filter(row => row.direction === 'outline').at(-1)?.beforeSeq)).toBe(1301)
    for (let i = 0; i < 12 && await panel.getByRole('button', { name: 'Load earlier', exact: true }).count(); i++) {
        await panel.getByRole('button', { name: 'Load earlier', exact: true }).click()
        await expect(panel.getByRole('button', { name: 'Loading…', exact: true })).toHaveCount(0)
    }
    await expect(panel.getByRole('button', { name: 'Load earlier', exact: true })).toHaveCount(0)
    await expect(panel.locator('[data-outline-count]')).toHaveAttribute('data-outline-count', '1400')
    expect(await page.evaluate(() => window.__probe.windowState())).toEqual(before)
    expect(await page.evaluate(() => window.__probe.requests.filter(row => row.direction === 'before' || row.direction === 'context'))).toEqual([])
    await panel.getByRole('searchbox', { name: 'Search outline items' }).fill('Fixture message 1250')
    await panel.getByRole('button', { name: /Fixture message 1250$/ }).click()
    await expect(page.getByText('Fixture message 1250', { exact: true })).toBeInViewport()
})

